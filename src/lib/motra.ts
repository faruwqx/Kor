const slug = (s: string) =>
  'm-' +
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

function build(rows: MRow[]): Exercise[] {
  return rows.map(([name, cats, gear]) => {
    const cat = cats.split('|')
    const equipment = GEAR2EQUIP[gear] ?? 'other'
    return {
      id: slug(name),
      name,
      muscle: CAT2MUSCLE[cat[0]] ?? 'core',
      equipment,
      load: equipment === 'bodyweight' ? 'bodyweight' : 'external',
      cats: cat,
      gear,
    }
  })
}


const NAMES: Record<'en' | 'es', Dict> = { en: EN, es: ES }

/** Yerleşik hareketin adı seçili dilde; bilinmeyen ad olduğu gibi döner. */
export function exLabel(tr: string, lang: Lang): string {
  if (lang === 'tr') return tr
  const names = NAMES[lang]
  const full = names[tr]
  if (full) return full
  const m = /^(.*) \((.*)\)$/.exec(tr)
  if (m) return `${names[m[1]] ?? m[1]} (${MODS[lang][m[2]] ?? m[2]})`
  return tr
}

